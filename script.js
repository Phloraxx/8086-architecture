    path.setAttribute('marker-end', `url(#${normalMarkerId})`); // Use unique marker ID
    path.style.cursor = 'pointer';
    path.style.pointerEvents = 'auto'; // Only the path is clickable

    console.log('Set marker-end to:', `url(#${normalMarkerId})`);

    // Add hover effects
