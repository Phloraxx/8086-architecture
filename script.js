// Drag and drop functions
function dragStart(e) {
    e.dataTransfer.setData('text/plain', e.target.dataset.component);
    setTimeout(() => {
        e.target.classList.add('dragging');
    }, 0);
}

function dragEnd(e) {
    e.target.classList.remove('dragging');
}

function dragOver(e) {
    e.preventDefault();
}

function dragEnter(e) {
    e.preventDefault();
    e.target.classList.add('drag-over');
}

function dragLeave(e) {
    e.target.classList.remove('drag-over');
}

function drop(e) {
    e.preventDefault();
    e.target.classList.remove('drag-over');

    const componentType = e.dataTransfer.getData('text/plain');
    if (componentType) {
        // Calculate mouse position relative to workspace
        const workspace = document.getElementById('workspace-area');
        const rect = workspace.getBoundingClientRect();
        const x = e.clientX - rect.left;
        const y = e.clientY - rect.top;
        createWorkspaceComponent(componentType, x, y);
    }
}

// Create component in workspace
function createWorkspaceComponent(componentType, x, y) {
    const workspace = document.getElementById('workspace-area');
    const component = document.createElement('div');
    component.className = 'workspace-component';
    component.dataset.component = componentType;
    component.style.left = (x - 60) + 'px';
    component.style.top = (y - 30) + 'px';
    
    // Add component content
    const img = document.createElement('img');
    img.src = componentInfo[componentType].image || (componentType + '.png');
    img.alt = componentInfo[componentType].name;
    img.width = 100;
    
    const name = document.createElement('p');
    name.textContent = componentInfo[componentType].name;
    
    component.appendChild(img);
    component.appendChild(name);
    
    // Add event listeners
    component.addEventListener('mousedown', startDragComponent);
    component.addEventListener('click', selectComponent);
    
    // Add connection points
    addConnectionPoints(component, componentType);
    
    workspace.appendChild(component);
}

