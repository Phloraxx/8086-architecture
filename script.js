    marker.setAttribute('orient', 'auto');
    marker.setAttribute('markerUnits', 'userSpaceOnUse');
    marker.setAttribute('viewBox', '0 0 20 20');
    
    const arrowPath = document.createElementNS(svgNS, 'path');
