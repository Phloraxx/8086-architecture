    // Get positions
    const startPos = getOffsetPosition(connection.from, connection.startPoint);
    const endPos = getOffsetPosition(connection.to, connection.endPoint);

    // Create path data
    const pathData = `M ${startPos.x} ${startPos.y} L ${endPos.x} ${endPos.y}`;
    path.setAttribute('d', pathData);
