    arrowPath.setAttribute('fill', '#3498db');
    arrowPath.setAttribute('stroke', '#2980b9');
    arrowPath.setAttribute('stroke-width', '2');
    
    marker.appendChild(arrowPath);
    defs.appendChild(marker);
    
    // Create the hover arrow marker
    const hoverMarker = document.createElementNS(svgNS, 'marker');
    hoverMarker.setAttribute('id', hoverMarkerId);
    hoverMarker.setAttribute('markerWidth', '20');
    hoverMarker.setAttribute('markerHeight', '20');
    hoverMarker.setAttribute('refX', '18');
    hoverMarker.setAttribute('refY', '10');
    hoverMarker.setAttribute('orient', 'auto');
    hoverMarker.setAttribute('markerUnits', 'userSpaceOnUse');
    hoverMarker.setAttribute('viewBox', '0 0 20 20');
    
